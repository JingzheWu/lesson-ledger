import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const storageKey = 'lesson-ledger:pricing:v1'
async function fillHours(page: Page, name: string, value: string, groupId = 0, gradeId = 0) {
  for (const target of [`group-${groupId}`, `grade-${gradeId}`]) {
    const button = page.locator(`button[aria-controls="${target}"]`)
    if (await button.getAttribute('aria-expanded') === 'false') await button.click()
  }
  await page.getByRole('textbox', { name, exact: true }).fill(value)
}
async function calculate(page: Page) { await page.getByRole('button', { name: '计算课时费', exact: true }).click() }
async function settings(page: Page) { await page.getByRole('button', { name: '计费设置', exact: true }).click() }
const firstPrice = (page: Page) => page.getByRole('textbox', { name: '第1阶梯一至五年级单价', exact: true })

test.beforeEach(async ({ page }) => { await page.goto('/') })

