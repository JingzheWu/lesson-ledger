test('B04：无效课时阻止计算并定位折叠区域里的错误', async ({ page }) => {
  await fillHours(page, '一年级一对一小时数', '10')
  await calculate(page)
  for (const value of ['-1', '文字', 'Infinity', '0.001']) {
    await fillHours(page, '六年级一对一小时数', value, 1, 5)
    await page.locator('button[aria-controls="group-1"]').click()
    await calculate(page)
    await expect(page.getByRole('textbox', { name: '六年级一对一小时数', exact: true })).toBeFocused()
    await expect(page.getByRole('textbox', { name: '六年级一对一小时数', exact: true })).toHaveAttribute('aria-invalid', 'true')
    await expect(page.getByTestId('total-fee')).toHaveText('¥150.00')
    await expect(page.locator('body')).not.toContainText('NaN')
  }
  await fillHours(page, '六年级一对一小时数', '0.01', 1, 5)
  await calculate(page)
  await expect(page.getByTestId('total-fee')).toHaveText('¥150.25')
})

