test('B01/B03/B08：保存价格、旧结果保留旧表、重算、刷新仅保留价格', async ({ page }) => {
  // Insecure LAN HTTP contexts may not expose randomUUID; pricing must still save.
  await page.evaluate(() => Object.defineProperty(crypto, 'randomUUID', { value: undefined }))
  await fillHours(page, '一年级一对一小时数', '10')
  await calculate(page)
  await settings(page)
  await firstPrice(page).fill('20')
  await page.getByRole('button', { name: '保存并应用' }).click()
  await expect(page.getByText('输入或规则已变化，请重新计算。下方明细和计费表为上次计算快照。')).toBeVisible()
  await expect(page.getByTestId('total-fee')).toHaveText('¥150.00')
  await expect(page.getByTestId('snapshot-price-0-0')).toHaveText('15.00')
  await calculate(page)
  await expect(page.getByTestId('total-fee')).toHaveText('¥200.00')
  await expect(page.getByTestId('snapshot-price-0-0')).toHaveText('20.00')
  await expect(page.locator('.stale-notice')).toHaveCount(0)
  expect(await page.evaluate(key => Object.keys(localStorage).filter(k => k === key || k.includes('lesson')), storageKey)).toEqual([storageKey])
  await page.reload()
  await expect(page.getByTestId('total-fee')).toHaveText('¥—')
  await expect(page.getByRole('textbox', { name: '一年级一对一小时数', exact: true })).toHaveValue('')
  await settings(page)
  await expect(firstPrice(page)).toHaveValue('20')
})

