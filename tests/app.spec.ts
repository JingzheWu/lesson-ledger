  await expect(explanation.getByRole('button', { name: '保存并应用' })).toHaveCount(0)
  await expect(explanation).toContainText('先计入一对一，再计入一对二，最后计入一对三')
  await expect(explanation).toContainText('每条最终明细四舍五入到分')
  await expect(page.getByRole('dialog', { name: '计费设置', exact: true })).toHaveCount(0)
  const close = explanation.getByRole('button', { name: '关闭计费说明' })
  await expect(close).toBeFocused()
